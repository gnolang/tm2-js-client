import {
  expect, test,
} from "vitest";

import {
  generate,
} from "./generate-errors.mjs";

const fixture = `package std

type FirstError struct{ abciError }
type (
  SecondError struct{ abciError }
)

func (e FirstError) Error() string { return "first error" }
func (e SecondError) Error() string { return "second error" }
`;

// SecondError is registered under a different name on purpose: the ID must
// come from the amino registration, not from the Go type name.
const packageFixture = `package std

var Package = amino.RegisterPackage(amino.NewPackage(
\t"github.com/gnolang/gno/tm2/pkg/std",
\t"std",
\tamino.GetCallersDirname(),
).WithDependencies().WithTypes(
\t&BaseAccount{}, "BaseAccount",
\tFirstError{}, "FirstError",
\tSecondError{}, "Second",
))
`;

test("generates classes and IDs in upstream order", () => {
  expect(generate(fixture, packageFixture)).toBe(`// Code generated by scripts/generate-errors.mjs from scripts/upstream/tm2/pkg/std/. DO NOT EDIT.

import {
  TM2Error,
} from "./errors.js";

export class FirstError extends TM2Error {
  constructor(log?: string) {
    super("first error", log);
  }
}

export class SecondError extends TM2Error {
  constructor(log?: string) {
    super("second error", log);
  }
}

export const stdErrors: Readonly<Record<string, new (log?: string) => TM2Error>> = Object.freeze({
  "/std.FirstError": FirstError,
  "/std.Second": SecondError,
});
`);
});

test.each([["missing Error()", `${fixture}\ntype MissingError struct{ abciError }`, packageFixture], ["missing struct", `${fixture}\nfunc (e ExtraError) Error() string { return "extra" }`, packageFixture], ["empty source", "package std", packageFixture], ["missing registration", fixture, packageFixture.replace("\tSecondError{}, \"Second\",\n", "")], ["missing package name", fixture, "package std"]])("rejects %s", (_name, errorsSource, packageSource) => {
  expect(() => generate(errorsSource, packageSource)).toThrow(/^std errors:/);
});
