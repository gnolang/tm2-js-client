import {
  readFileSync, writeFileSync,
} from "node:fs";
import process from "node:process";
import {
  fileURLToPath, URL,
} from "node:url";

const upstreamDir = new URL("./upstream/tm2/pkg/std/", import.meta.url);
const output = new URL("../src/provider/errors/std.ts", import.meta.url);

/**
 * Generates the std error classes from upstream errors.go (types and
 * messages) and package.go (amino registrations, which define the IDs)
 * @param {string} errorsSource tm2/pkg/std/errors.go
 * @param {string} packageSource tm2/pkg/std/package.go
 * @returns {string} the TypeScript module
 */
export function generate(errorsSource, packageSource) {
  const structs = new Set(Array.from(errorsSource.matchAll(/\b(\w+)\s+struct\s*\{\s*abciError\s*\}/g), match => match[1]));
  const errors = Array.from(errorsSource.matchAll(/^func \(e (\w+)\) Error\(\) string\s*\{ return ("(?:[^"\\\r\n]|\\.)*") \}$/gm));
  const methods = new Set(errors.map(match => match[1]));
  const pkg = /NewPackage\(\s*"[^"]*",\s*"(\w+)"/.exec(packageSource)?.[1];
  const registered = new Map(Array.from(packageSource.matchAll(/^\s*&?(\w+)\{\}, "(\w+)",/gm), match => [match[1], match[2]]));

  const missingMethods = [...structs].filter(name => !methods.has(name));
  const missingStructs = [...methods].filter(name => !structs.has(name));
  const unregistered = [...structs].filter(name => !registered.has(name));

  if (!pkg || !structs.size || missingMethods.length || missingStructs.length || unregistered.length) {
    throw new Error(`std errors: each struct{ abciError } needs one Error() method and a package.go registration; package: ${pkg ?? "not found"}; without Error(): ${missingMethods.join(", ") || "none"}; without struct: ${missingStructs.join(", ") || "none"}; unregistered: ${unregistered.join(", ") || "none"}`);
  }

  const classes = errors.map(([, name, message]) => `export class ${name} extends TM2Error {
  constructor(log?: string) {
    super(${message}, log);
  }
}`).join("\n\n");
  const entries = errors.map(([, name]) => `  "/${pkg}.${registered.get(name)}": ${name},`).join("\n");

  return `// Code generated by scripts/generate-errors.mjs from scripts/upstream/tm2/pkg/std/. DO NOT EDIT.

import {
  TM2Error,
} from "./errors.js";

${classes}

export const stdErrors: Readonly<Record<string, new (log?: string) => TM2Error>> = Object.freeze({
${entries}
});
`;
}

export function writeStdErrors() {
  const read = file => readFileSync(new URL(file, upstreamDir), "utf8");
  writeFileSync(output, generate(read("errors.go"), read("package.go")));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeStdErrors();
}
